import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const data = {
  CATEGORIES: JSON.parse(fs.readFileSync(path.join(root, "data/categories.json"), "utf8")),
  TRACKS: JSON.parse(fs.readFileSync(path.join(root, "data/tracks.json"), "utf8")),
  PRODUCTS: JSON.parse(fs.readFileSync(path.join(root, "data/products.json"), "utf8")),
  TIMELINES: JSON.parse(fs.readFileSync(path.join(root, "data/timelines.json"), "utf8")),
  SOURCES: JSON.parse(fs.readFileSync(path.join(root, "data/sources.json"), "utf8")),
  META: JSON.parse(fs.readFileSync(path.join(root, "data/meta.json"), "utf8")),
  NEWS: fs.existsSync(path.join(root, "data/news.json"))
    ? JSON.parse(fs.readFileSync(path.join(root, "data/news.json"), "utf8"))
    : { items: {} },
};

const out = `/* generated by scripts/build-data.mjs — edit JSON under /data, then rebuild */
const CATALOG = ${JSON.stringify(data, null, 2)};
`;
fs.mkdirSync(path.join(root, "js"), { recursive: true });
fs.writeFileSync(path.join(root, "js/data.js"), out);
console.log("wrote js/data.js", data.PRODUCTS.length, "products");
